"""Reports written by the PUBLISHED regaudit-fhe 0.1.0 must keep verifying as TRUSTED.

tests/vectors/published_0_1_0/ holds report.v1 and report.v2 files produced by the 0.1.0
source (commit 600066fe7f3f4c0b85be057f2e5f1569083862af), installed into a separate
virtualenv, with a throwaway key whose private half was discarded (synthetic data only).
They are NOT regenerated by this suite: that is the point. If strict parsing ever refuses
one of them, existing evidence has changed meaning and that is a compatibility break.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

import pytest

import regaudit_fhe as rf
from regaudit_fhe.report_v2 import parse_envelope, parse_envelope_strict

VEC = Path(__file__).parent / "vectors" / "published_0_1_0"
REPORTS = sorted(p.name for p in VEC.glob("v[12]_*.json"))
STORES = ["trust_store_entries.json", "trust_store_legacy.json"]


def test_the_fixture_set_is_complete_and_unmodified():
    manifest = json.loads((VEC / "MANIFEST.json").read_text())
    assert manifest["version"] == "0.1.0"
    assert manifest["source_commit"] == "600066fe7f3f4c0b85be057f2e5f1569083862af"
    assert len(REPORTS) == 16
    for name, digest in manifest["sha256"].items():
        assert hashlib.sha256((VEC / name).read_bytes()).hexdigest() == digest, name
    assert set(manifest["sha256"]) >= set(REPORTS) | set(STORES)


@pytest.mark.parametrize("store_name", STORES)
@pytest.mark.parametrize("name", REPORTS)
def test_verify_trusted_accepts_every_published_report(name, store_name):
    store = rf.TrustStore.from_json(VEC / store_name)
    out = rf.verify_trusted((VEC / name).read_text(encoding="utf-8"), store)
    assert out.verdict is rf.TrustVerdict.TRUSTED, (out.reasons, out.detail)


@pytest.mark.parametrize("name", REPORTS)
def test_the_strict_parser_reads_exactly_what_the_published_writer_wrote(name):
    text = (VEC / name).read_text(encoding="utf-8")
    assert parse_envelope_strict(text).to_dict() == parse_envelope(text).to_dict()
    assert json.loads(parse_envelope_strict(text).to_json()) == json.loads(text)


@pytest.mark.parametrize("name", REPORTS)
def test_the_lenient_engine_path_agrees_with_the_strict_one(name):
    store = rf.TrustStore.from_json(VEC / "trust_store_entries.json")
    env = parse_envelope((VEC / name).read_text(encoding="utf-8"))
    assert rf.verify_report(env, rf.VerificationPolicy(trust_store=store)).trust_status == "TRUSTED"


@pytest.mark.parametrize("name", REPORTS)
def test_a_changed_published_report_is_not_trusted(name):
    store = rf.TrustStore.from_json(VEC / "trust_store_entries.json")
    data = json.loads((VEC / name).read_text(encoding="utf-8"))
    data["issued_at"] = "2020-01-01T00:00:00+00:00"
    assert not rf.verify_trusted(json.dumps(data), store).trusted


@pytest.mark.parametrize("name", ["v1_fairness.json", "v2_fairness.json", "v1_with_dp.json"])
def test_cli_verify_exits_zero_for_published_reports(name):
    proc = subprocess.run(  # noqa: S603 - fixed argv
        [
            sys.executable,
            "-m",
            "regaudit_fhe.cli",
            "verify",
            "-i",
            str(VEC / name),
            "--trusted-keys",
            str(VEC / "trust_store_entries.json"),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    assert json.loads(proc.stdout)["trust_status"] == "TRUSTED"
